// The Great Replanting's islands as data (conductor kr-arcade/t-070..t-072, CABINETS.md
// section 9): each wilted island is five short landing puzzles and a boss set-piece, every one a
// MissionSpec. Later slices add islands to ISLANDS; a save can point one past the last, waiting.
//
//   1 Meadow Isle (dawn): today's hills, wider; updraft vents; First Bloom; Old Scarecrow.
//   2 Windmill Downs: gust lanes, windmills, dandelion drift and crow-bots; Pollen Post; the Gale Mill.
//   3 Waterfall Gorge: waterfalls, drip stalactites and pebble rollers; Thirsty Terraces (carry
//     water bubbles to dry beds); the Geyser Tortoise.
//   4 Firefly Caverns: dark caves lit by your glow, crystal bumpers, spore puffballs; Lantern Run
//     (relight the cave), Rescue (tow stranded sprout-bots home); the Glowworm Queen.
//   5 Storm Shelf: rain-heavy skies (gravity up), sun seeds, sky farms; Thunderhead (t-072).
//   6 Moon Garden: low gravity, no wind, huge inertia; meteor streaks; the Old Lander (t-072).

