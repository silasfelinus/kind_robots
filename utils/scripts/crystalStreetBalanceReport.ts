/**
 * Terrors on Crystal Street balance report (conductor crystal-street t-006).
 *
 * Plays seeded weeks with the careful autoplay (near-optimal) and the
 * careless one (random legal play) and prints a Markdown report: the ending
 * mix overall, per nightmare, per clique, per look and per style, Typecast
 * against Against type, and how often each special ending fires.
 *
 *   npx tsx utils/scripts/crystalStreetBalanceReport.ts [--runs 96]
 *
 * --runs is weeks per nightmare per policy (default 96: every clique, and
 * looks rotating so each one meets every nightmare at least three times).
 */
import { autoplay, carelessAutoplay } from '../crystalStreet/autoplay'
import {
  ARCHETYPES,
  AVATARS,
  STYLE_LABELS,
  VILLAINS,
  synergyOf,
} from '../crystalStreet/rules'
import type { RunState } from '../crystalStreet/rules'
import type { VillainId } from '../crystalStreet/ids'

const flag = process.argv.indexOf('--runs')
const RUNS = flag > 0 ? Number(process.argv[flag + 1]) : 96

type Week = {
  villain: string
  clique: string
  look: string
  style: string
  typecast: boolean
  run: RunState
}

function play(policy: 'careful' | 'careless'): Week[] {
  const weeks: Week[] = []
  for (const v of VILLAINS) {
    for (let i = 0; i < RUNS; i++) {
      const clique = ARCHETYPES[i % ARCHETYPES.length]!
      const look = AVATARS[(i * 7 + v.id.length) % AVATARS.length]!
      const seed = `balance-${policy}-${v.id}-${i}`
      const run =
        policy === 'careful'
          ? autoplay(seed, v.id as VillainId, clique.id, look.id)
          : carelessAutoplay(seed, v.id as VillainId, clique.id, look.id)
      weeks.push({
        villain: v.id,
        clique: clique.id,
        look: look.id,
        style: look.style,
        typecast: !!synergyOf(look.id, clique.id)?.typecast,
        run,
      })
    }
  }
  return weeks
}

const pct = (n: number, total: number) =>
  total ? `${Math.round((n / total) * 100)}%` : '–'

function mix(weeks: Week[]) {
  const count = (test: (w: Week) => boolean) => weeks.filter(test).length
  const tier = (t: string) => (w: Week) =>
    w.run.ending?.tier === t &&
    w.run.ending?.special !== 'family' &&
    w.run.ending?.special !== 'officials' &&
    w.run.ending?.special !== 'neighbors'
  const collapse = (w: Week) =>
    ['family', 'officials', 'neighbors'].includes(w.run.ending?.special ?? '')
  return {
    n: weeks.length,
    best: count(tier('best')),
    good: count(tier('good')),
    bittersweet: count(tier('bittersweet')),
    bad: count(tier('bad')),
    collapse: count(collapse),
    finalGirl: count((w) => w.run.ending?.special === 'final-girl'),
  }
}

function row(label: string, weeks: Week[]): string {
  const m = mix(weeks)
  return `| ${label} | ${m.n} | ${pct(m.best, m.n)} | ${pct(m.good, m.n)} | ${pct(m.bittersweet, m.n)} | ${pct(m.bad, m.n)} | ${pct(m.collapse, m.n)} | ${pct(m.finalGirl, m.n)} |`
}

const HEAD =
  '| | Weeks | Best | Good | Bittersweet | Bad | Collapse | Final Girl |\n| --- | --- | --- | --- | --- | --- | --- | --- |'

function table(
  title: string,
  weeks: Week[],
  key: (w: Week) => string,
  label: (k: string) => string = (k) => k,
  sortByBest = true,
): string {
  const groups = new Map<string, Week[]>()
  for (const w of weeks) groups.set(key(w), [...(groups.get(key(w)) ?? []), w])
  const keys = [...groups.keys()]
  if (sortByBest)
    keys.sort(
      (a, b) =>
        mix(groups.get(a)!).best / mix(groups.get(a)!).n -
        mix(groups.get(b)!).best / mix(groups.get(b)!).n,
    )
  return [
    `### ${title}`,
    '',
    HEAD,
    ...keys.map((k) => row(label(k), groups.get(k)!)),
  ].join('\n')
}

const careful = play('careful')
const careless = play('careless')
const name = (id: string) => VILLAINS.find((v) => v.id === id)?.name ?? id
const cliqueName = (id: string) =>
  ARCHETYPES.find((a) => a.id === id)?.name ?? id
const lookName = (id: string) => AVATARS.find((a) => a.id === id)?.name ?? id

const bestRate = (weeks: Week[]) => mix(weeks).best / mix(weeks).n
const perVillain = VILLAINS.map((v) => ({
  id: v.id,
  rate: bestRate(careful.filter((w) => w.villain === v.id)),
}))
const outside = perVillain.filter((r) => r.rate < 0.4 || r.rate > 0.75)
const typecast = bestRate(careful.filter((w) => w.typecast))
const against = bestRate(careful.filter((w) => !w.typecast))

console.log(
  [
    '# Terrors on Crystal Street: balance report',
    '',
    `Generated by \`utils/scripts/crystalStreetBalanceReport.ts --runs ${RUNS}\`: ${RUNS} weeks per nightmare per policy, every clique, looks rotating. *Careful* is the near-optimal autoplay (best odds, mends a standing at 1); *careless* plays random legal moves. *Collapse* is a faction special ending (Grounded, Blamed, Run Out of the Cul-de-Sac); *Final Girl* is a Final Girl win.`,
    '',
    '## Targets (roadmap #4143)',
    '',
    `- Every nightmare 40–75% Best under careful play: ${outside.length ? `**${outside.length} outside** (${outside.map((r) => `${name(r.id)} ${Math.round(r.rate * 100)}%`).join(', ')})` : 'all inside'}.`,
    `- Typecast vs Against type within 5 points: Typecast ${Math.round(typecast * 100)}%, Against type ${Math.round(against * 100)}% (${Math.abs(Math.round((typecast - against) * 100))} points).`,
    `- Careless play survives most weeks: ${pct(careless.filter((w) => w.run.ending?.tier !== 'bad').length, careless.length)} avoid the bad ending.`,
    '',
    '## Overall',
    '',
    HEAD,
    row('Careful', careful),
    row('Careless', careless),
    '',
    '## Careful play',
    '',
    table('By nightmare', careful, (w) => w.villain, name),
    '',
    table('By clique', careful, (w) => w.clique, cliqueName),
    '',
    table('By look', careful, (w) => w.look, lookName),
    '',
    table(
      'By style',
      careful,
      (w) => w.style,
      (k) => STYLE_LABELS[k as keyof typeof STYLE_LABELS],
    ),
    '',
    table('Typecast vs Against type', careful, (w) =>
      w.typecast ? 'Typecast' : 'Against type',
    ),
    '',
    '## Careless play',
    '',
    table('By nightmare', careless, (w) => w.villain, name),
  ].join('\n'),
)
