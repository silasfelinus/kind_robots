export function personalFinaleNode(
  node: SceneNode,
  lead: string,
  stageId: string,
  campaign: boolean,
  state: Pick<TrainingState, 'crossfireCast' | 'units'>,
): SceneNode {
  if (
    !campaign ||
    stageId !== 'prom-night-finale' ||
    state.crossfireCast !== 2 ||
    !Object.hasOwn(PERSONAL_FINALE_LINES, lead)
  )
    return node
  const index = FINALE_NODE_IDS.indexOf(node.id)
  const text = PERSONAL_FINALE_LINES[lead]?.[index]
  if (!text) return node
  const ally = state.units.find(
    (unit) => unit.team === 'squad' && unit.id !== 'backdraft' && unit.hp > 0,
  )
  const supportingLine =
    [
      'c1',
      'cs',
      'cc',
      's1',
      'j1',
      't2',
      'f1',
      'p2',
      'l1',
      'x1',
      'vs',
      'vc',
    ].includes(node.id) &&
    !LEAD_SPOKEN[lead]?.includes(node.id)
  const speaker = supportingLine ? (ally?.id ?? 'backdraft') : 'backdraft'
  return { ...node, speaker, text }
}
