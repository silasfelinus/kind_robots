// /utils/scripts/create-component-json.mjs
import { createHash } from 'node:crypto'
import { promises as fs } from 'node:fs'
import path from 'node:path'
import { extractWonderLabComponentSourceEvidence } from '../wonderlab/componentSourceEvidence.mjs'

const ROOT = process.cwd()
const COMPONENT_ROOT = path.resolve(ROOT, 'components')
const MANIFEST_OUTPUT = path.resolve(ROOT, 'public/wonderlab-components.json')
const EVIDENCE_OUTPUT = path.resolve(
  ROOT,
  'utils/generated/wonderLabSourceEvidence.ts',
)

// Test scaffolding is not an exhibit and never was.
const ignoredSegments = new Set(['__tests__', '__fixtures__'])

/**
 * Retired components are PARKED here, not deleted.
 *
 * They are excluded from Nuxt auto-import (nuxt.config.ts's `ignore` resolves
 * relative to `~/components`) and from vue-tsc (tsconfig `exclude`), so they
 * cost the app nothing — but they are still real files, so WonderLab can still
 * mount them and their exhibits keep working. Skipping them here would drop
 * them from the manifest, which makes reconcile flip `isDiscovered: false` and
 * the museum report them as missing: exactly the outcome parking exists to
 * avoid. So they are walked and FLAGGED instead.
 */
const ABANDONWARE_SEGMENT = 'abandonware'

function isAbandoned(relativePath) {
  return toPosix(relativePath).split('/').includes(ABANDONWARE_SEGMENT)
}

function toPosix(value) {
  return value.split(path.sep).join('/')
}

function toSlug(value) {
  return value
    .replace(/\.vue$/i, '')
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/[^a-zA-Z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .toLowerCase()
}

function shouldIgnore(relativePath) {
  const segments = toPosix(relativePath).split('/')
  return segments.some((segment) => ignoredSegments.has(segment))
}

async function collectVueFiles(directory, files = []) {
  const entries = await fs.readdir(directory, { withFileTypes: true })

  for (const entry of entries) {
    const absolutePath = path.join(directory, entry.name)
    const relativePath = path.relative(COMPONENT_ROOT, absolutePath)

    if (shouldIgnore(relativePath)) continue

    if (entry.isDirectory()) {
      await collectVueFiles(absolutePath, files)
      continue
    }

    if (entry.isFile() && entry.name.endsWith('.vue')) {
      files.push(absolutePath)
    }
  }

  return files
}

async function buildManifestEntry(absolutePath) {
  const relativePath = toPosix(path.relative(COMPONENT_ROOT, absolutePath))
  const sourcePath = `components/${relativePath}`
  const folderName = toPosix(path.dirname(relativePath))
  const componentName = path.basename(relativePath, '.vue')
  const source = await fs.readFile(absolutePath, 'utf8')
  const sourceHash = createHash('sha256').update(source).digest('hex')

  return {
    sourceKey: sourcePath.toLowerCase(),
    sourcePath,
    sourceHash,
    componentName,
    slug: toSlug(relativePath),
    folderName: folderName === '.' ? 'root' : folderName,
    abandoned: isAbandoned(relativePath),
    sourceEvidence: extractWonderLabComponentSourceEvidence(source),
  }
}

function evidenceModule(entries) {
  const registry = Object.fromEntries(
    entries.map((entry) => [
      entry.sourcePath.toLowerCase(),
      entry.sourceEvidence,
    ]),
  )
  return [
    "import type { WonderLabComponentSourceEvidence } from '@/utils/wonderlab/componentManifest'",
    '',
    '// Generated by utils/scripts/create-component-json.mjs before every Nuxt build.',
    'export const wonderLabSourceEvidenceByPath: Readonly<',
    '  Record<string, WonderLabComponentSourceEvidence>',
    `> = ${JSON.stringify(registry, null, 2)}`,
    '',
  ].join('\n')
}

function publicManifestEntry(entry) {
  const { sourceEvidence: _sourceEvidence, ...publicEntry } = entry
  return publicEntry
}

async function generateComponentManifest() {
  const files = await collectVueFiles(COMPONENT_ROOT)
  const entries = await Promise.all(files.map(buildManifestEntry))
  entries.sort((left, right) =>
    left.sourcePath.localeCompare(right.sourcePath, 'en'),
  )

  const manifest = {
    version: 1,
    generatedAt: new Date().toISOString(),
    componentRoot: 'components',
    count: entries.length,
    entries: entries.map(publicManifestEntry),
  }

  await Promise.all([
    fs.mkdir(path.dirname(MANIFEST_OUTPUT), { recursive: true }),
    fs.mkdir(path.dirname(EVIDENCE_OUTPUT), { recursive: true }),
  ])
  await Promise.all([
    fs.writeFile(MANIFEST_OUTPUT, `${JSON.stringify(manifest, null, 2)}\n`),
    fs.writeFile(EVIDENCE_OUTPUT, evidenceModule(entries)),
  ])

  console.log(
    `Generated ${entries.length} WonderLab component entries and source evidence.`,
  )
}

generateComponentManifest().catch((error) => {
  console.error('Failed to generate WonderLab component manifest:', error)
  process.exitCode = 1
})
