export function personalCrosswalkNode(
  node: SceneNode,
  lead: string,
  stageId: string,
  campaign: boolean,
  state: Pick<TrainingState, 'crossfireCast' | 'units'>,
): SceneNode {
  if (
    !campaign ||
    stageId !== 'crosswalk-crisis' ||
    state.crossfireCast !== 2 ||
    !Object.hasOwn(PERSONAL_CROSSWALK_LINES, lead)
  )
    return node
  const index = CROSSWALK_NODE_IDS.indexOf(node.id)
  const text = PERSONAL_CROSSWALK_LINES[lead]?.[index]
  if (!text) return node
  const ally = state.units.find(
    (unit) => unit.team === 'squad' && unit.id !== 'backdraft' && unit.hp > 0,
  )
  const speaker = ['s1', 'sm', 'sj', 'r1', 'wj', 'wm'].includes(node.id)
    ? (ally?.id ?? 'backdraft')
    : 'backdraft'
  return { ...node, speaker, text }
}
