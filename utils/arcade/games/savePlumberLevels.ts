const SOLIDS: Record<string, number> = {
  '#': SOLID_GROUND,
  B: SOLID_BLOCK,
  '=': SOLID_LEDGE,
  g: SOLID_GATE,
  D: SOLID_PIPE,
  E: SOLID_PIPE,
  c: SOLID_CRATE,
  w: SOLID_WATER,
  '<': SOLID_BELT_LEFT,
  '>': SOLID_BELT_RIGHT,
  ':': SOLID_BRIDGE,
}

/** The top cell of each vertical run of `mark`, left to right. */
function pipeTops(def: StageDef, mark: string) {
  const tops: { col: number; row: number }[] = []
  def.rows.forEach((line, row) => {
    for (let col = 0; col < line.length; col++)
      if (line[col] === mark && def.rows[row - 1]?.[col] !== mark)
        tops.push({ col, row })
  })
  return tops.sort((a, b) => a.col - b.col || a.row - b.row)
}

export function parseStage(def: StageDef): Stage {
  const rows = def.rows.length
  const cols = def.rows[0]!.length
  if (def.rows.some((line) => line.length !== cols))
    throw new Error(`stage ${def.code}: ragged rows`)
  const solid = new Uint8Array(cols * rows)
  const spawns: Spawn[] = []
  let start: { col: number; row: number } | null = null
  let gate: number | null = null
  def.rows.forEach((line, row) => {
    for (let col = 0; col < cols; col++) {
      const ch = line[col]!
      if (SOLIDS[ch]) solid[row * cols + col] = SOLIDS[ch]!
      else if (SPAWNS[ch]) spawns.push({ kind: SPAWNS[ch]!, col, row })
      else if (ch === '@') start = { col, row }
      else if (ch === 'X') gate = col
      else if (ch !== '.') throw new Error(`stage ${def.code}: unknown "${ch}"`)
      if (ch === 'm') solid[row * cols + col] = SOLID_WATER
    }
  })
  if (!start) throw new Error(`stage ${def.code}: no start`)
  const entries = pipeTops(def, 'D')
  const exits = pipeTops(def, 'E')
  if (entries.length !== exits.length)
    throw new Error(`stage ${def.code}: unpaired pipe doors`)
  const doors: Door[] = []
  entries.forEach((entry, i) => {
    doors.push({ ...entry, to: doors.length + 1 })
    doors.push({ ...exits[i]!, to: doors.length - 1 })
  })
  return {
    code: def.code,
    name: def.name,
    cols,
    rows,
    solid,
    start,
    spawns,
    doors,
    gate,
    dark: def.dark === true,
  }
}
