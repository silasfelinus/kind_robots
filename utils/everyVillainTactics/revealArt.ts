/**
 * Every comic popup resolves its own actor and role, not the lead villain's
 * face. Private ArtImages load using the authenticated tactics art store;
 * failed fetches keep the established public Prom artwork fallback.
 */
export function paintedRevealArtId(
  intro: Pick<ComicIntro, 'key' | 'role'> | null,
): number | null {
  if (!intro) return null
  if (intro.role === 'hero' || intro.role === 'villain')
    return PAINTED_EVT_REVEAL_ART[intro.key] ?? null
  if (intro.role === 'henchman' || intro.role === 'lieutenant')
    return PAINTED_EVT_SUPPORT_ART[intro.key] ?? null
  return null
}
