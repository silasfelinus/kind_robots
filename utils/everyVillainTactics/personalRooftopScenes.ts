const LEAD_SPOKEN: Readonly<Record<string, readonly string[]>> = {
  'magic-birthright': ['s1'],
  'tech-earth': ['t1'],
  'tech-genius': ['c1', 't1'],
  'mutant-fire': ['c1', 'cw'],
  'mutant-air': ['t1'],
  'psychic-earth': ['s1'],
  'psychic-genius': ['w1'],
}

export function personalRooftopNode(
  node: SceneNode,
  lead: string,
  stageId: string,
  campaign: boolean,
  state: Pick<TrainingState, 'crossfireCast' | 'units'>,
): SceneNode {
  if (
    !campaign ||
    stageId !== 'rooftop-broadcast' ||
    state.crossfireCast !== 2 ||
    !Object.hasOwn(PERSONAL_ROOFTOP_LINES, lead)
  )
    return node
  const index = ROOFTOP_NODE_IDS.indexOf(node.id)
  const text = PERSONAL_ROOFTOP_LINES[lead]?.[index]
  if (!text) return node
  const ally = state.units.find(
    (unit) => unit.team === 'squad' && unit.id !== 'backdraft' && unit.hp > 0,
  )
  const supportingLine =
    ['c1', 'cw', 'cj', 'w1', 'j1', 't1', 's1', 'vw', 'vj'].includes(node.id) &&
    !LEAD_SPOKEN[lead]?.includes(node.id)
  const speaker = supportingLine ? (ally?.id ?? 'backdraft') : 'backdraft'
  return { ...node, speaker, text }
}
