/**
 * Save the Plumber's authored stages (conductor save-the-plumber t-006, t-007,
 * t-008, t-009, t-010): World 1 Bluebell Pipeworks, World 2 Tideglass Marina,
 * World 3 Lantern Orchard, World 4 Clockwork Fair, World 5 Cloudrail Commons,
 * World 6 Crystal Underworks, World 7 Night Market Rooftops and World 8
 * Stardrain Citadel. Each stage is a hand-drawn tile map, 16px per character,
 * 24 rows tall with the ground surface on row 21 (three rows above the
 * bottom); the camera scrolls up when the heroine climbs into the top rows.
 * Edit the rows to change a stage; verifySavePlumberLevels.test.ts plays every
 * stage through.
 *
 *   .  empty          #  ground           B  block           =  one-way ledge
 *   g  valve gate     v  valve switch     o  brass token     c  wooden crate
 *   p  pumpbug        r  rivet roller     ^  steam vent      s  springstep
 *   P  piston (rises and falls)           L  brass lift (slides side to side)
 *   K  checkpoint     G  goal valve       D  pipe door       E  secret-room pipe
 *   @  start          X  boss gate        M  the world's boss
 *   w  water          F  bobbing raft     m  clockwork minnow (leaps from water)
 *   k  cork crab      u  glass gull       l  moss lantern     h  spring hare
 *   <  belt carrying left                 >  belt carrying right
 *   j  gasket golem   y  paper kite       n  umbrella mite
 *   ~  wind corridor (the whole column gusts a headwind)
 *   Q  cargo drop (crates fall here and rest a moment as steps)
 *   :  crystal bridge (solid only while it glows)
 *   i  puddle mimic   z  siphon sprite    t  chimney spirit   T  tea-kettle knight
 *   1  Springstep power   2  Bottled Storm power   3  Pocket Lift power
 *   +  water heart (restores a heart)
 *   *  the stage's Golden Gear (one per stage, harder to reach each world)
 */

