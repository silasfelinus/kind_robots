export function personalBreachNode(
  node: SceneNode,
  lead: string,
  stageId: string,
  campaign: boolean,
  state: Pick<TrainingState, 'crossfireCast' | 'units'>,
): SceneNode {
  if (
    !campaign ||
    stageId !== 'under-comet-breach' ||
    state.crossfireCast !== 2 ||
    !Object.hasOwn(PERSONAL_BREACH_LINES, lead)
  )
    return node
  const index = BREACH_NODE_IDS.indexOf(node.id)
  const text = PERSONAL_BREACH_LINES[lead]?.[index]
  if (!text) return node
  const ally = state.units.find(
    (unit) => unit.team === 'squad' && unit.id !== 'backdraft' && unit.hp > 0,
  )
  const supportingLine =
    ['c1', 'cv', 'ce', 'v1', 'e1', 't1', 'f1', 's1', 'wv', 'we'].includes(
      node.id,
    ) && !LEAD_SPOKEN[lead]?.includes(node.id)
  const speaker = supportingLine ? (ally?.id ?? 'backdraft') : 'backdraft'
  return { ...node, speaker, text }
}
